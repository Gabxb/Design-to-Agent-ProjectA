## 安装和运行

### 环境要求
- Python 3.12
- Docker

### 安装步骤
```bash
# 克隆仓库
git clone [repository-url]

# 创建虚拟环境
python -m venv venv
source venv/bin/activate  # Linux/Mac
# 或 venv\Scripts\activate  # Windows

# 安装依赖
pip install -r requirements.txt

# 启动服务
python main.py
```

